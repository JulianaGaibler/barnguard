// Builds the blue-noise tile the dither effect reads and writes it next to the
// effect as base64. See core/render/dither/blueNoiseGenerator.ts.
//
// Usage: npm run gen:blue-noise

import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { createServer } from 'vite'

const out = fileURLToPath(
  new URL('../src/core/render/dither/blueNoise64.gen.ts', import.meta.url),
)

const server = await createServer({
  configFile: fileURLToPath(new URL('../vite.config.ts', import.meta.url)),
  server: { middlewareMode: true, hmr: false },
  optimizeDeps: { noDiscovery: true, entries: [] },
  appType: 'custom',
  logLevel: 'error',
})
try {
  const noise = await server.ssrLoadModule(
    '/src/core/render/dither/blueNoiseGenerator.ts',
  )
  const started = performance.now()
  const tile = noise.generateBlueNoise(noise.BLUE_NOISE_SIZE)
  writeFileSync(
    out,
    `// Generated by scripts/genBlueNoise.mjs. Do not edit.\n\n` +
      `/** ${noise.BLUE_NOISE_SIZE} by ${noise.BLUE_NOISE_SIZE} tile, one byte per cell, row by row. */\n` +
      `export const BLUE_NOISE_BASE64 =\n  '${Buffer.from(tile).toString('base64')}'\n`,
  )
  console.log(`wrote ${out} in ${Math.round(performance.now() - started)} ms`)
} finally {
  await server.close()
}
